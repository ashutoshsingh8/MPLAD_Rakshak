/**
 * Helper to get localized state name
 */
export function getLocalizedState(stateName, lang = 'en') {
  if (!stateName) return '';
  const cleanLang = lang ? lang.split('-')[0] : 'en';
  const entry = STATE_TRANSLATIONS[stateName];
  if (entry && entry[cleanLang]) return entry[cleanLang];
  if (entry && entry.en) return entry.en;
  return stateName;
}

/**
 * Helper to get localized district name
 */
export function getLocalizedDistrict(districtName, lang = 'en') {
  if (!districtName) return '';
  const cleanLang = lang ? lang.split('-')[0] : 'en';
  let entry = DISTRICT_TRANSLATIONS[districtName];
  if (!entry) {
    const key = Object.keys(DISTRICT_TRANSLATIONS).find(
      (k) => k.toLowerCase() === districtName.toLowerCase().trim()
    );
    if (key) entry = DISTRICT_TRANSLATIONS[key];
  }
  if (entry && entry[cleanLang]) return entry[cleanLang];
  if (entry && entry.en) return entry.en;
  return districtName;
}
