/**
 * Return localized project title based on project_uid or title string
 */
export function getLocalizedProjectTitle(project, lang = 'en') {
  if (!project) return '';
  const cleanLang = lang ? lang.split('-')[0] : 'en';

  const uid = project.project_uid || (project.id ? `MPLAD-2024-MH-00${project.id}` : null);
  if (uid && PROJECT_TITLE_TRANSLATIONS[uid]) {
    const entry = PROJECT_TITLE_TRANSLATIONS[uid];
    if (entry[cleanLang]) return entry[cleanLang];
  }

  // Look for match in titles
  if (project.title) {
    for (const item of Object.values(PROJECT_TITLE_TRANSLATIONS)) {
      if (item.en && item.en.toLowerCase() === project.title.toLowerCase()) {
        if (item[cleanLang]) return item[cleanLang];
      }
    }
  }

  return project.title || '';
}

/**
 * Return localized contractor dossier details
 */
export function getLocalizedContractorDivision(division, district, lang = 'en') {
  if (!division) return '';
  const cleanLang = lang ? lang.split('-')[0] : 'en';
  if (cleanLang === 'hi') {
    return `${district || 'पुणे'} जिला परिषद एवं लोक निर्माण प्रभाग`;
  }
  if (cleanLang === 'mr') {
    return `${district || 'पुणे'} जिल्हा परिषद आणि सार्वजनिक बांधकाम विभाग`;
  }
  if (cleanLang === 'bn') {
    return `${district || 'পুনে'} জেলা পরিষদ ও গণপূর্ত বিভাগ`;
  }
  if (cleanLang === 'ta') {
    return `${district || 'புனே'} மாவட்ட பஞ்சாயத்து மற்றும் பொதுப்பணித்துறை`;
  }
  if (cleanLang === 'te') {
    return `${district || 'పూణే'} జిల్లా పరిషత్ మరియు ప్రజా పనుల విభాగం`;
  }
  if (cleanLang === 'gu') {
    return `${district || 'પુણે'} જિલ્લા પંચાયત અને માર્ગ-મકાન વિભાગ`;
  }
  if (cleanLang === 'kn') {
    return `${district || 'ಪುಣೆ'} ಜಿಲ್ಲಾ ಪಂಚಾಯತ್ ಮತ್ತು ಲೋಕೋಪಯೋಗಿ ಇಲಾಖೆ`;
  }
  if (cleanLang === 'ur') {
    return `${district || 'پونے'} ضلع پریشد اور محکمہ تعمیرات عامہ`;
  }
  return division;
}
